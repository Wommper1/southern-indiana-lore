package com.example.data.local

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.example.data.model.ConfidenceLevel
import com.example.data.model.LoreSite

@Entity(
    tableName = "lore_sites",
    indices = [
        Index(value = ["latitude", "longitude"])
    ]
)
data class LoreSiteEntity(
    @PrimaryKey val id: String,
    val title: String,
    val subtitle: String,
    val category: String,
    val county: String = "Floyd County",
    val latitude: Double,
    val longitude: Double,
    val address: String,
    val era: String,
    val accessStatus: String,
    val fullStory: String,
    val verifiedHistory: String = "",
    val folkloreTradition: String = "",
    val confidenceLevel: String = ConfidenceLevel.VERIFIED.name,
    val sources: String = "",
    val sourceNotes: String,
    val verificationGrade: String,
    val geofenceRadiusMeters: Int,
    val audioNarration: String,
    val isFavorite: Boolean = false,
    val isVisited: Boolean = false,
    val userNotes: String = "",
    val lastVisitedTimestamp: Long = 0L,
    val isCustom: Boolean = false,
    val photoUri: String? = null,
    // Proximity Historian Dimensions:
    val alternativeNames: String = "",
    val siteType: String = "POINT",
    val subType: String = "",
    val triggerRadiusType: String = "LOCAL_SITE",
    val driveStory: String = "",
    val whyHere: String = "",
    val historyNerdDiscovery: String = "",
    val aboveLayer: String = "",
    val surfaceLayer: String = "",
    val belowLayer: String = "",
    val time1800: String = "",
    val time1850: String = "",
    val time1900: String = "",
    val time1950: String = "",
    val timeToday: String = "",
    val whatMayBeUnderground: String = "",
    val visibleRemains: String = "",
    val relatedLocations: String = "",
    val relatedPeople: String = "",
    val relatedEvents: String = "",
    val mapEvidence: String = "",
    val unresolvedQuestions: String = "",
    val accessLevel: String = "PUBLIC ACCESS",
    val isSensitiveLocation: Boolean = false,
    val isExactCoordinateSafe: Boolean = true,
    val radarType: String = "HISTORIC_NEARBY",
    val youJustCrossedEvent: String = "",
    val geometryCoordinates: String = "",
    val undergroundConfidence: String = "",
    val encounterCount: Int = 0,
    val firstDiscoveredTimestamp: Long = 0L,
    val lastEncounterTimestamp: Long = 0L,
    val hasListenedAudio: Boolean = false
) {
    fun toDomain(distance: Float = 0f): LoreSite {
        val parsedConfidence = ConfidenceLevel.fromString(confidenceLevel)

        return LoreSite(
            id = id,
            title = title,
            subtitle = subtitle,
            category = category,
            county = county,
            latitude = latitude,
            longitude = longitude,
            address = address,
            era = era,
            accessStatus = accessStatus,
            fullStory = fullStory,
            verifiedHistory = if (verifiedHistory.isNotBlank()) verifiedHistory else fullStory,
            folkloreTradition = folkloreTradition,
            confidenceLevel = parsedConfidence,
            sources = if (sources.isNotBlank()) sources else sourceNotes,
            sourceNotes = sourceNotes,
            verificationGrade = verificationGrade,
            geofenceRadiusMeters = geofenceRadiusMeters,
            audioNarration = audioNarration,
            isFavorite = isFavorite,
            isVisited = isVisited,
            userNotes = userNotes,
            lastVisitedTimestamp = lastVisitedTimestamp,
            distanceMeters = distance,
            isCustom = isCustom,
            photoUri = photoUri,
            alternativeNames = alternativeNames,
            siteType = siteType,
            subType = subType,
            triggerRadiusType = triggerRadiusType,
            driveStory = if (driveStory.isNotBlank()) driveStory else subtitle,
            whyHere = whyHere,
            historyNerdDiscovery = historyNerdDiscovery,
            aboveLayer = if (aboveLayer.isNotBlank()) aboveLayer else title,
            surfaceLayer = if (surfaceLayer.isNotBlank()) surfaceLayer else address,
            belowLayer = if (belowLayer.isNotBlank()) belowLayer else whatMayBeUnderground,
            time1800 = time1800,
            time1850 = time1850,
            time1900 = time1900,
            time1950 = time1950,
            timeToday = if (timeToday.isNotBlank()) timeToday else "Modern landscape & preserved historical site",
            whatMayBeUnderground = whatMayBeUnderground,
            visibleRemains = visibleRemains,
            relatedLocations = relatedLocations,
            relatedPeople = relatedPeople,
            relatedEvents = relatedEvents,
            mapEvidence = mapEvidence,
            unresolvedQuestions = unresolvedQuestions,
            accessLevel = if (accessLevel.isNotBlank()) accessLevel else accessStatus,
            isSensitiveLocation = isSensitiveLocation,
            isExactCoordinateSafe = isExactCoordinateSafe,
            radarType = if (radarType.isNotBlank()) radarType else "HISTORIC_NEARBY",
            youJustCrossedEvent = youJustCrossedEvent,
            geometryCoordinates = geometryCoordinates,
            undergroundConfidence = undergroundConfidence,
            encounterCount = encounterCount,
            firstDiscoveredTimestamp = firstDiscoveredTimestamp,
            lastEncounterTimestamp = lastEncounterTimestamp,
            hasListenedAudio = hasListenedAudio
        )
    }
}
